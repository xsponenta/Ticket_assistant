"""Render reports/03_data_preparation.md from data/processed/prep_stats.json and splits.json.

Usage:
    python src/data/report_prep.py
"""

from __future__ import annotations

import json
from typing import Any

from prep_stats import PROCESSED, ROOT, load_stats

CLASSES = ["bug", "feature", "task", "idea"]
SPLITS = ["train", "val", "test"]
REPORT = ROOT / "reports" / "03_data_preparation.md"


def table(header: list[str], rows: list[list[Any]]) -> str:
    def fmt(v: Any) -> str:
        return f"{v:,}" if isinstance(v, int) else str(v)
    lines = ["| " + " | ".join(header) + " |",
             "|" + "|".join("---:" if any(isinstance(r[i], (int, float)) for r in rows) else "---" for i in range(len(header))) + "|"]
    lines += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in rows]
    return "\n".join(lines)


def pct(n: int, total: int) -> str:
    return f"{100 * n / total:.1f}%" if total else "—"


def main() -> None:
    s = load_stats()
    missing = [k for k in ("prepare", "splits", "eval", "doc_chunks") if k not in s]
    if missing:
        raise SystemExit(f"prep_stats.json lacks {missing}: run prepare.py, split.py, build_eval.py, chunk_docs.py first.")
    p, sp, ev, dc = s["prepare"], s["splits"], s["eval"], s["doc_chunks"]
    d1, d3, txt, dup = p["d1_mapping"], p["d3_date_range"], p["text"], p["duplicates"]
    splits = json.loads((PROCESSED / "splits.json").read_text())
    main_n = d3["main"]

    out: list[str] = []
    w = out.append
    w("# 03 · Data Preparation (part 1, deterministic)\n")
    w("_Generated by `python src/data/report_prep.py` from `data/processed/prep_stats.json`. No LLM calls are used in "
      "any step. Decisions D1–D5 with alternatives and evidence: [`decisions.md`](decisions.md)._\n")

    w("## Pipeline\n")
    w(table(["Step", "Script", "Output"], [
        ["1. Clean text (Jira → Markdown, PII D5, whitespace)", "`src/data/clean.py` (used by step 2)", "—"],
        ["2. Map, filter, clean (D1–D3, D5)", "`src/data/prepare.py`", "`data/processed/issues.parquet`, `drift_2026.parquet`"],
        ["3. Stratified, duplicate-aware split (frozen)", "`src/data/split.py`", "`data/processed/splits.json`"],
        ["4. Evaluation sets", "`src/data/build_eval.py`", "`data/eval/*.jsonl`, `data/eval/README.md`"],
        ["5. Doc chunks", "`src/data/chunk_docs.py`", "`data/processed/doc_chunks.jsonl`"],
        ["6. Manual scope labels", "`src/data/label_cli.py`", "`data/eval/scope_labeled.jsonl`"],
        ["7. This report", "`src/data/report_prep.py`", "`reports/03_data_preparation.md`"],
    ]))
    w("")

    # ---------------- counts before / after
    w("## Counts before / after each step\n")
    w(table(["Step", "Before", "After", "Note"], [
        ["Load raw", "—", p["raw"]["spark_issues.jsonl"] + p["raw"]["spark_wish_all.jsonl"],
         f"`spark_issues.jsonl` {p['raw']['spark_issues.jsonl']:,} + `spark_wish_all.jsonl` {p['raw']['spark_wish_all.jsonl']:,}; "
         "`wish_other.jsonl` not used (D2)"],
        ["Union by key", p["raw"]["spark_issues.jsonl"] + p["raw"]["spark_wish_all.jsonl"], p["union"]["unique_issues"],
         f"{p['union']['wish_in_both_files']} SPARK Wish issues are in both files"],
        ["D1 mapping", d1["before"], d1["after"], f"{d1['before'] - d1['after']:,} excluded (Sub-task {d1['excluded_by_type'].get('Sub-task', 0):,})"],
        ["D3 date range → main", d3["before"], d3["main"], f"created {d3['main_created_range'][0]} … {d3['main_created_range'][1]}"],
        ["D3 date range → drift set", d3["before"], d3["drift_2026"], "all issues created in 2026 (all classes)"],
        ["Split (train / val / test)", main_n, sum(sp["totals"].values()),
         " / ".join(f"{sp['totals'][x]:,}" for x in SPLITS)],
    ]))
    w("")
    w("**Excluded issue types (D1)**\n")
    w(table(["Issue type", "Issues"], [[t, n] for t, n in d1["excluded_by_type"].items()]))
    w("")
    w("**Kept issue types → class, main vs drift (D1, D3)**\n")
    class_of = {"Bug": "bug", "New Feature": "feature", "Improvement": "feature", "Story": "feature", "Task": "task",
                "Test": "task", "Documentation": "task", "Dependency upgrade": "task", "Wish": "idea", "Brainstorming": "idea"}
    w(table(["Issue type", "Class", "Kept (all years)", "Main", "Drift 2026"], [
        [t, class_of[t], n, d3["main_by_type"].get(t, 0), d3["drift_by_type"].get(t, 0)] for t, n in d1["kept_by_type"].items()]))
    w("")
    w(f"Idea has no lower date bound (D3): {d3['idea_before_2020']} of the {d3['main_by_class']['idea']} idea issues in main were "
      f"created before 2020. The {d3['idea_in_2026_moved_to_drift']} SPARK Wish issues created in 2026 are in the drift set, "
      "like every other 2026 issue.\n")

    w("**Class distribution: main dataset vs drift set**\n")
    w(table(["Class", "Main", "Main %", "Drift 2026", "Drift %"], [
        [c, d3["main_by_class"][c], pct(d3["main_by_class"][c], main_n), d3["drift_by_class"][c],
         pct(d3["drift_by_class"][c], d3["drift_2026"])] for c in CLASSES]))
    w("")

    # ---------------- cleaning
    w("## Text cleaning and PII masking (D5)\n")
    w("`clean_description()` = Jira wiki markup → Markdown, then PII masking, then whitespace normalisation:\n")
    w("- **Code blocks:** `{code}` / `{noformat}` become fenced blocks (language kept). Code is protected while the rest is converted.")
    w("- **Headings and quotes:** `h1.`–`h6.` → `#`…`######`; `{quote}` and `bq.` → `>`.")
    w("- **Links:** `[text|url]` → `[text](url)`; `[url]` → `<url>`.")
    w("- **Inline:** `{{mono}}` → `` `mono` ``; `{color}` tags are stripped.")
    w("- **Extras:** Jira `#`/`*` lists → Markdown lists, table header rows, images, and Jira editor artifacts (see `decisions.md`).")
    w("- **Summaries:** PII masking and whitespace normalisation only.")
    w("- **Tests:** 20 test cases built from real snippets are in `tests/test_clean.py`.\n")
    w(table(["Main dataset", "Issues", "% of main"], [
        ["Description contains `<EMAIL>`", txt["main_with_email_mask"], pct(txt["main_with_email_mask"], main_n)],
        ["Description contains `<USER>`", txt["main_with_user_mask"], pct(txt["main_with_user_mask"], main_n)],
        ["URL credentials removed", txt["main_raw_with_url_credentials"], pct(txt["main_raw_with_url_credentials"], main_n)],
        ["Description has a fenced code block", txt["main_with_code_block"], pct(txt["main_with_code_block"], main_n)],
        ["Empty description (`has_description = false`)", txt["main_empty_description"], pct(txt["main_empty_description"], main_n)],
        ["Empty summary", txt["main_empty_summary"], pct(txt["main_empty_summary"], main_n)],
    ]))
    w("")
    w(table(["Class", "Empty descriptions", "% of class"], [
        [c, txt["main_empty_description_by_class"][c], pct(txt["main_empty_description_by_class"][c], d3["main_by_class"][c])]
        for c in CLASSES]))
    w("")
    w(f"**Duplicate links:**")
    w(f"- {dup['main_issues_with_duplicate_of']:,} main issues have `duplicate_of` and {dup['main_issues_with_duplicated_by']:,} have `duplicated_by`.")
    w(f"- {dup['pairs_both_in_main']:,} pairs have both issues in the main dataset.")
    w("- Direction follows EDA §5.\n")

    # ---------------- splits
    w("## Splits (D4)\n")
    w(f"- **Method:** stratified by `target_class`, 70 / 15 / 15, seed {splits['seed']}. "
      f"Issues connected by Duplicate links form a group, and each group goes to one split.")
    w(f"- **Groups:** {sp['duplicate_groups_size_ge_2']:,} groups of size ≥ 2, the largest with {sp['largest_duplicate_group']} issues. "
      f"No Duplicate pair crosses splits (checked by an assertion in `split.py`).")
    w(f"- **Frozen:** `split.py` refuses to overwrite an existing `splits.json`. The test-key hash is `{sp['test_sha256'][:16]}…`.\n")
    rows = []
    for c in CLASSES:
        n = sum(sp["counts"][x][c] for x in SPLITS)
        rows.append([c] + [sp["counts"][x][c] for x in SPLITS] + [n] + [pct(sp["counts"][x][c], n) for x in SPLITS])
    rows.append(["**total**"] + [sp["totals"][x] for x in SPLITS] + [sum(sp["totals"].values())]
                + [pct(sp["totals"][x], sum(sp["totals"].values())) for x in SPLITS])
    w(table(["Class", "Train", "Val", "Test", "Total", "Train %", "Val %", "Test %"], rows))
    w("")
    w(table(["Class"] + [f"{x} class share" for x in SPLITS], [
        [c] + [pct(sp["counts"][x][c], sp["totals"][x]) for x in SPLITS] for c in CLASSES]))
    w("")

    # ---------------- eval sets
    w("## Evaluation sets (`data/eval/`, details in `data/eval/README.md`)\n")
    ct, du, sc, si = ev["classification_test"], ev["duplicates"], ev["scope_candidates"], ev["simulator_candidates"]
    w(table(["File", "Rows", "Composition"], [
        ["`classification_test.jsonl`", ct["rows"], ", ".join(f"{c} {ct['by_class'][c]}" for c in CLASSES)
         + f"; {ct['empty_description']} with empty description"],
        ["`duplicates.jsonl`", du["duplicate_queries"] + du["non_duplicate_queries"],
         f"{du['duplicate_queries']} duplicate + {du['non_duplicate_queries']} non-duplicate queries"],
        ["`scope_candidates.jsonl`", sc["rows"], ", ".join(f"{b} {sc[b]['selected']}" for b in
                                                            ("fixed", "declined", "not_a_problem_or_invalid", "incomplete"))
         + f" (feature {sc['by_class']['feature']}, idea {sc['by_class']['idea']})"],
        ["`simulator_candidates.jsonl`", si["rows"], ", ".join(f"{c} {min(15, si[c]['eligible'])}/{si[c]['eligible']} eligible" for c in CLASSES)],
    ]))
    w("")
    w("**a. Classification test.**")
    w(f"- Test split, at most 100 per class. Available in test: {', '.join(f'{c} {ct['available_in_test'][c]}' for c in CLASSES)}.")
    w("- Labels: `target_class` (issue type → D1) and `components` (Jira).\n")
    w("**b. Duplicates.**")
    w("- A Jira `Duplicate` link is treated as **undirected**: the later-created issue of a pair is the query, "
      "the earlier one is gold (a user writing a new ticket must find the existing one).")
    w("- Both issues must be in the main dataset. The corpus is the main-dataset issues created before the query, "
      "so gold is always retrievable.\n")
    w(table(["Duplicate pairs", "Count"], [
        ["Linked pairs with both issues in the main dataset", du["undirected_pairs_both_in_main"]],
        ["… Jira marks the later issue as the duplicate (same direction as the query)",
         du["pairs_where_jira_duplicate_is_the_later_issue"]],
        ["… Jira marks the earlier issue as the duplicate (direction flipped for retrieval)",
         du["pairs_where_jira_duplicate_is_the_earlier_issue"]],
        ["− identical normalised summaries (trivial)", du["excluded_identical_normalised_summary"]],
        ["= valid pairs", du["valid_pairs"]],
        ["Duplicate queries (one per later issue)", du["duplicate_queries"]],
        ["… linked to several earlier issues (`gold` = oldest, `gold_all` = all)", du["queries_with_multiple_gold"]],
        ["Non-duplicate queries (`gold: null`)", du["non_duplicate_queries"]],
    ]))
    w("")
    w(f"Duplicate queries by split: {', '.join(f'{x} {du['duplicate_queries_by_split'][x]}' for x in SPLITS)}. "
      f"By class: {', '.join(f'{c} {du['duplicate_queries_by_class'][c]}' for c in CLASSES)}.\n")
    w("**c. Scope candidates.**")
    w("- Resolved feature/idea issues with a non-empty description.")
    w("- The Jira resolution is stored as `resolution_hint`, not as a label.\n")
    w(table(["Bucket", "Resolutions", "Selected", "From test", "From val", "From train", "Available in test"], [
        [b, r, sc[b]["selected"], sc[b]["per_split"]["test"], sc[b]["per_split"]["val"], sc[b]["per_split"]["train"],
         sc[b]["available_in_test"]] for b, r in [("fixed", "Fixed"), ("declined", "Won't Fix / Won't Do / Later"),
                                                  ("not_a_problem_or_invalid", "Not A Problem / Invalid"), ("incomplete", "Incomplete")]]))
    w("")
    w("**d. Simulator candidates.**")
    w("- Test split, rich descriptions: bug = ≥ 3 of the 4 EDA signals; other classes = ≥ 80 words.")
    w("- At most 15 per class; the final selection is made later with an LLM.\n")
    w(table(["Class", "Test issues with description", "Eligible", "Selected"], [
        [c, si[c]["test_with_description"], si[c]["eligible"], min(15, si[c]["eligible"])] for c in CLASSES]))
    w("")

    # ---------------- docs
    w("## Doc chunks\n")
    if dc.get("generated_reference_chunks"):
        w("- **CRISP-DM iteration (2026-11-15).** The generated reference tables were missing from the corpus. "
          "`sql-ref-functions-builtin.md` and `configuration.md` include them with `{% include_api_gen %}` at site-build time, "
          "and this step stripped Liquid tags, so the SQL built-in functions and the runtime/static SQL configs were lost. "
          "Found during C3 modelling, where requests such as \"json_array_length\" could not be confirmed from the docs. "
          "Fix: `src/data/fetch_doc_tables.py` stores the rendered pages (`data/raw/docs_generated/`), and "
          "`chunk_docs.py` adds their tables on `<page>__generated` pages. All existing chunk ids and texts are unchanged.")
        w("- **CRISP-DM iteration 2 (2026-11-15).** As 111 list chunks of ~40 entries, the reference was still not "
          "retrieved for single-function requests (one entry is diluted in its list). It is now chunked one entry per chunk "
          f"(`entry_chunks`, prefix `title > heading`): {dc['generated_reference_chunks']} chunks. They are short "
          "by design and account for most chunks under 300 tokens below.")
    t = dc["tokens"]
    w(f"- **Input:** Spark {dc['version']} docs, {dc['pages_in']} pages; skipped {', '.join(dc['pages_skipped'])}; "
      f"{dc['pages_chunked']} pages chunked.")
    w("- **Cleaning:** front matter stripped (title kept); Liquid tags and `include_example` lines removed; "
      "`{% highlight %}` blocks turned into ``` fences.")
    w("- **Splitting:** on headers of any level, outside code. Each chunk is prefixed with `title > header path`.")
    w(f"- **Size:** target {300}–{500} tokens ({dc['tokenizer']}, counted on the final chunk text).\n")
    w(table(["Chunks", "Tokens total", "min", "p10", "median", "p90", "max", "< 300", "300–500", "> 500"], [[
        dc["chunks"], dc["tokens_total"], t["min"], t["p10"], t["median"], t["p90"], t["max"],
        f"{100 * dc['share_lt_300']:.1f}%", f"{100 * dc['share_300_500']:.1f}%", f"{100 * dc['share_gt_500']:.1f}%"]]))
    w("")
    w("Chunks under 300 tokens are short pages, or short sections followed by a section too large to merge with.")
    w("Small trailing chunks are first merged into the previous chunk of the same page when that stays within 500.\n")

    # ---------------- notes
    np_ = sc["not_a_problem_or_invalid"]
    w("## Notes and limitations (accepted)\n")
    w("**Scope candidates: top-up from val.**")
    w(f"- The test split has only {np_['available_in_test']} resolved feature/idea issues with a description in the "
      f"Not A Problem / Invalid bucket.")
    w(f"- The remaining {np_['per_split']['val']} were drawn from val (field `split` in `scope_candidates.jsonl`).")
    w("- All other buckets come entirely from test.\n")
    w("**Simulator candidates: thin classes.**")
    w(f"- Only {si['task']['eligible']} task and {si['idea']['eligible']} idea issues in test have ≥ 80 words.")
    w("- These two classes therefore get 15 from a small pool, so the later LLM selection has little to choose from.")
    w(f"- Bug and feature have {si['bug']['eligible']} and {si['feature']['eligible']} eligible issues.\n")
    w("**Token counts are a proxy.**")
    w(f"- Chunk sizes are measured with `{dc['tokenizer']}`, not the tokenizer of the model that will consume the chunks.")
    w("- Counts for other tokenizers typically differ by about 10–20%, so the 300–500 target is approximate.\n")

    # ---------------- decisions
    w("## Decisions applied (details and alternatives: [`decisions.md`](decisions.md))\n")
    w(table(["ID", "Decision", "Evidence (EDA)", "Effect here"], [
        ["D1", "bug = Bug; feature = New Feature, Improvement, Story; task = Task, Test, Documentation, Dependency upgrade; "
               "idea = Wish, Brainstorming; all other types excluded (incl. Sub-task)",
         "Sub-task 39% of SPARK, 55.8% empty, fragments of other types (§1, §2, §4a)",
         f"{d1['before']:,} → {d1['after']:,} issues"],
        ["D2", "idea = SPARK Wish all-time + Brainstorming; `wish_other` unused",
         "63% of `wish_other` name their project; Spark mentioned in 1.5% vs 72.8% of SPARK Wish (§4b)",
         f"idea = {d3['main_by_class']['idea']} issues"],
        ["D3", "main = created before 2026 (non-idea from 2020-01-01, idea without lower bound); "
               "everything created in 2026 → drift set (all classes)",
         "2026 bugs: 2× longer, Jira headings 11.6%, root cause / fix 11.4%, PR label 89% (§10)",
         f"main {d3['main']:,}, drift {d3['drift_2026']:,}"],
        ["D4", "no resampling; stratified splits; macro-F1; class weights allowed",
         f"idea {pct(d3['main_by_class']['idea'], main_n)} and task {pct(d3['main_by_class']['task'], main_n)} of main (§1)",
         "70/15/15 per class, duplicate-aware"],
        ["D5", "e-mail → `<EMAIL>`, `[~user]` / `@user` → `<USER>`, URL credentials removed, URLs kept",
         "mentions 0.4%, e-mails 0.1% of descriptions, summaries clean (§8)",
         f"{txt['main_with_email_mask']} / {txt['main_with_user_mask']} / {txt['main_raw_with_url_credentials']} issues masked "
         "(e-mail / user / credentials)"],
    ]))
    w("")

    REPORT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"Wrote {REPORT}")


if __name__ == "__main__":
    main()
